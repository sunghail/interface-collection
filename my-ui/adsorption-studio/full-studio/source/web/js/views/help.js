let pop = null;
let anchorEl = null;

export function helpTip(key) {
  const entry = HELP[key];
  if (!entry) return null;
  return h("button.help-tip", { type: "button", title: `${entry.title} — 눌러서 설명 보기`, onclick: (e) => {
    e.preventDefault();
    e.stopPropagation();
    const same = pop && anchorEl === e.currentTarget;
    closeHelp();
    if (!same) openHelp(entry, e.currentTarget);
  } }, [h("span.help-q", {}, "?"), "설명"]);
}

/** A small table; a long one is split into two side by side so the card stays short. */
function helpTable({ head, rows }) {
  const half = rows.length > 6 ? Math.ceil(rows.length / 2) : rows.length;
  const part = (list) => h("table.help-table", {}, [
    h("thead", {}, h("tr", {}, head.map((x) => h("th", {}, x)))),
    h("tbody", {}, list.map((r) => h("tr", {}, r.map((x) => h("td", {}, x))))),
  ]);
  return h("div.help-tables", {}, [part(rows.slice(0, half)), rows.length > half ? part(rows.slice(half)) : null]);
}

function openHelp(entry, anchor) {
  const list = (items) => h("ul.help-list", {}, items.map((x) => h("li", {}, x)));
  pop = h("div.help-pop", { role: "dialog", "aria-label": entry.title }, [
    h("div.help-head", {}, [h("b", {}, entry.title), h("button.icon-btn", { title: "닫기", onclick: closeHelp }, "✕")]),
    h("p.help-what", {}, entry.what),
    entry.how ? h("div.help-sec", {}, [h("div.help-label", {}, entry.howLabel || "알아둘 점"), list(entry.how)]) : null,
    entry.table ? helpTable(entry.table) : null,
    entry.unknown ? h("div.help-sec", {}, [h("div.help-label", {}, "모르면"), h("p", {}, entry.unknown)]) : null,
    entry.example ? h("div.help-example", {}, [h("span.help-label", {}, "예 "), entry.example]) : null,
  ]);
  anchorEl = anchor;
  document.body.append(pop);
  place();
}

function place() {
  if (!pop || !anchorEl) return;
  if (!anchorEl.isConnected) { closeHelp(); return; }            // the view was redrawn under it
  const a = anchorEl.getBoundingClientRect();
  const w = pop.offsetWidth, ht = pop.offsetHeight;
  const vw = document.documentElement.clientWidth, vh = window.innerHeight;
  const left = Math.min(Math.max(8, a.left), vw - w - 8);
  const below = a.bottom + 6;
  const top = below + ht <= vh - 8 || a.top - ht - 6 < 8 ? Math.min(below, Math.max(8, vh - ht - 8)) : a.top - ht - 6;
  Object.assign(pop.style, { left: `${left}px`, top: `${top}px` });
}

export function closeHelp() {
  pop?.remove();
  pop = null;
  anchorEl = null;
}

document.addEventListener("pointerdown", (e) => {
  if (pop && !pop.contains(e.target) && !e.target.closest?.(".help-tip")) closeHelp();
});
// Esc closes only the card, not the input window under it
document.addEventListener("keydown", (e) => { if (e.key === "Escape" && pop) { e.stopPropagation(); closeHelp(); } }, true);
window.addEventListener("resize", place);
document.addEventListener("scroll", place, true);
